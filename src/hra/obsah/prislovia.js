// Rozdelí príslovie na časti pred a za chýbajúcim slovom
export function rozober(prislovie) {
  const m = prislovie.match(/^(.*)\{(.+?)\}(.*)$/);
  return { pred: m[1], slovo: m[2], za: m[3], cele: prislovie.replace(/[{}]/g, '') };
}
